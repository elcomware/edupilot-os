// Emit the same Core palette that the native client imports directly.
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("./palette.json", import.meta.url);
const target = new URL("./palette.css", import.meta.url);
const palette = JSON.parse(readFileSync(source, "utf8"));
const rules = Object.entries(palette).map(([theme, colors]) => {
  const selector = theme === "light" ? ":root" : ':root[data-theme="dark"]';
  const declarations = Object.entries(colors).map(([name, value]) => "  --ep-" + name + ": " + value + ";");
  return [selector + " {", ...declarations, "}"].join("\n");
});
const css = "/* Generated by build-palette.mjs from palette.json. */\n" + rules.join("\n") + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== css) throw new Error("Regenerate the Core brand palette.");
} else {
  writeFileSync(target, css);
}
