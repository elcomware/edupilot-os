#!/usr/bin/env python3
"""Create new workspace packages and rebuild the registry from modules/catalog.tsv.

Existing module files belong to their owners and are never overwritten.
"""
import argparse
import csv
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = "github.com/elcomware/edupilot"
GROUPS = {"platform", "lifecycle", "academics", "finance", "operations", "engagement"}


def emit(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text(content.strip() + "\n")


def scaffold(group, key, en, fr):
    root = ROOT / "modules" / key
    prefix = BASE + "/modules/" + key
    labels = f'catalog.Title{{EN: {json.dumps(en, ensure_ascii=False)}, FR: {json.dumps(fr, ensure_ascii=False)}}}'
    descriptor = f'catalog.Descriptor{{Key: "{key}", Group: "{group}", Title: {labels}, Capabilities: []string{{"list", "create", "update"'
    descriptor += ', "archive"}}' if key == "students" else '}}'
    # Display names and capabilities have one editable source, catalog.tsv.
    # Rewrite only generated descriptors; owner-maintained wiring stays intact.
    root.mkdir(parents=True, exist_ok=True)
    (root / "descriptor_generated.go").write_text(f"""// Code generated by scripts/scaffold-modules.py. DO NOT EDIT.
package {key}

import "{BASE}/platform/catalog"

func Descriptor() catalog.Descriptor {{ return {descriptor} }}
""")
    if key == "students":
        return
    emit(root / "internal/domain/workspace.go", f"""
// Package domain names the workspace owned by the {en} module.
// Its specialized business aggregates belong beside this definition.
package domain

const Key = "{key}"
""")
    emit(root / "application/workspace.go", f"""
package application

import "{BASE}/platform/workspace"

// Entries is the public use case for this module's school work list.
type Entries = workspace.Service

// Repository is the persistence port accepted by the application.
type Repository interface {{ workspace.Repository }}
""")
    emit(root / "adapters/outbound/persistence/repository.go", f"""
package persistence

import (
 "{prefix}/application"
 "{prefix}/internal/domain"
 "{BASE}/platform/database"
 "{BASE}/platform/workspace/sqlstore"
)

func New(catalog *database.Catalog) application.Repository {{
 return sqlstore.New(catalog, domain.Key)
}}
""")
    emit(root / "migrations/workspace.go", f"""
package migrations

import (
 "{prefix}/internal/domain"
 "{BASE}/database/edumigrations"
 "{BASE}/platform/workspace/sqlstore"
)

// WorkspaceSchema belongs to this module and runs on shared and dedicated databases.
func WorkspaceSchema() edumigrations.Plan {{ return sqlstore.Schema(domain.Key) }}
""")
    emit(root / "module.go", f"""
// Package {key} exposes the integration surface of the {en} module.
package {key}

import (
 "{prefix}/application"
 "{prefix}/adapters/outbound/persistence"
 "{prefix}/migrations"
 "{BASE}/modules/modulekit"
 "{BASE}/platform/database"
)

func Definition() modulekit.Definition {{
 return modulekit.Definition{{
  Descriptor: Descriptor(),
  Bind: func(db *database.Catalog) application.Entries {{
   return application.Entries{{Store: persistence.New(db)}}
  }},
  Migration: migrations.WorkspaceSchema,
 }}
}}
""")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", choices=sorted(GROUPS))
    args = parser.parse_args()
    with (ROOT / "modules/catalog.tsv").open() as source:
        rows = list(csv.reader(source, delimiter="\t"))
    seen = set()
    for group, key, en, fr in rows:
        if group not in GROUPS or not re.fullmatch(r"[a-z][a-z0-9_]{0,39}", key) or key in seen or not en or not fr:
            raise ValueError(f"Invalid catalog row for {key}")
        seen.add(key)
        if args.group is None or args.group == group:
            scaffold(group, key, en, fr)
    if args.group is not None:
        return
    imports = "\n".join(f' "{BASE}/modules/{key}"' for _, key, _, _ in rows)
    defs = ",\n".join(
        "  {Descriptor: students.Descriptor()}" if key == "students" else f"  {key}.Definition()"
        for _, key, _, _ in rows)
    registry = ROOT / "modules/all_generated.go"
    registry.write_text(f"""// Code generated by scripts/scaffold-modules.py. DO NOT EDIT.
package modules

import (
 "{BASE}/modules/modulekit"
{imports}
)

func Definitions() []modulekit.Definition {{
 return []modulekit.Definition{{
{defs},
 }}
}}
""")
    subprocess.run(["gofmt", "-w", *[str(p) for p in (ROOT/"modules").rglob("*.go")]], check=True)


if __name__ == "__main__":
    main()
